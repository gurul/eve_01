"""Write src/scripts.rs: app_check.py's page scripts as Rust raw strings, byte for byte.

    python3 rust/crates/eve-app-check/tools/gen_scripts.py

The test `the_page_scripts_are_pythons` reads app_check.py and fails when a script here drifts from it.
"""
import ast
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SRC = HERE.parent.parent.parent / "bridge" / "src" / "eve_bridge" / "app_check.py"
NAMES = ["STUBS_JS", "CONTROLS_JS", "REACH_JS", "PRESS_JS", "ERRORS_JS", "VIEW_JS", "CLOSE_JS", "LOOK_JS",
         "BAR_JS", "LAYOUT_JS"]

tree = ast.parse(SRC.read_text())
values = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        if node.targets[0].id in NAMES:
            values[node.targets[0].id] = node.value.value
out = ["//! app_check.py's page scripts, byte for byte. Generated by tools/gen_scripts.py; do not edit by hand.", ""]
for name in NAMES:
    v = values[name]
    hashes = 1
    while '"' + "#" * hashes in v:
        hashes += 1
    h = "#" * hashes
    out.append(f"pub const {name}: &str = r{h}\"{v}\"{h};")
    out.append("")
(HERE / "src" / "scripts.rs").write_text("\n".join(out))
print("wrote", len(NAMES), "scripts")
